// iTunes 单曲/EP 后缀对"专辑"属性无意义，统一剥掉
const SINGLE_SUFFIX = /\s*[-–—]\s*(single|ep)\s*$/i;

export function toSimplified(str) {
  if (!str) return str;
  let out = '';
  for (const ch of String(str)) out += (T2S[ch] || ch);
  return out.replace(SINGLE_SUFFIX, '').trim();
}